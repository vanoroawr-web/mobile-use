def _iter_app_items(app_mapping=None):
    app_mapping = app_mapping or APP_MAPPING
    if isinstance(app_mapping, dict):
        package_to_record = {}
        for app_name, package_name in app_mapping.items():
            if package_name not in package_to_record:
                package_to_record[package_name] = {
                    "name": app_name,
                    "package": package_name,
                    "aliases": [],
                }
            else:
                package_to_record[package_name]["aliases"].append(app_name)
        return list(package_to_record.values())
    return app_mapping


def build_alias_mapping(app_mapping=None):
    """Return every app name and alias -> package name."""
    alias_mapping = {}
    for item in _iter_app_items(app_mapping):
        names = [item["name"], *item.get("aliases", [])]
        for name in names:
            alias_mapping[name] = item["package"]
    return alias_mapping


# Backward-compatible flat mapping used by older integrations.
COLOR_MOBILE_APP_MAPPING = build_alias_mapping()


def build_package_to_app(app_mapping=None):
    """Return package -> canonical app name, preserving APP_MAPPING order."""
    package_to_app = {}
    for item in _iter_app_items(app_mapping):
        package_to_app.setdefault(item["package"], item["name"])
    return package_to_app


def build_app_to_package(app_mapping=None):
    """Return canonical app name -> package name."""
    return {item["name"]: item["package"] for item in _iter_app_items(app_mapping)}


def get_canonical_app_names(app_mapping=None):
    return list(build_app_to_package(app_mapping).keys())


def format_app_names_for_planner(app_names=None):
    app_names = app_names or get_canonical_app_names()
    return "、".join(app_names) if app_names else "未提供"


def resolve_app_package(app_name):
    """Resolve a Chinese app name, alias, or package name to an Android package name."""
    if not app_name:
        return app_name
    app_name = app_name.strip()
    alias_mapping = COLOR_MOBILE_APP_MAPPING
    if app_name in alias_mapping:
        return alias_mapping[app_name]
    return app_name
